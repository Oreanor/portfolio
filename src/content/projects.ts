export function getProjects(locale: Locale = "en"): Project[] {
  return projects.map((project) => ({
    ...project,
    ...(locale === "en" ? {} : projectTranslations[locale][project.slug]),
    gameplay: gameplay[locale][project.slug],
  }));
}

export function getProject(slug: string, locale: Locale = "en") {
  return getProjects(locale).find((project) => project.slug === slug);
}
